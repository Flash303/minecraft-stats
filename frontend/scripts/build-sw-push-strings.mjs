/**
 * Extracts the `notifications.push` subset from every `app/locales/*.json`
 * into `app/service-worker/push-strings.generated.ts`.
 *
 * Single source of truth stays `app/locales/*.json`: this script only
 * copies the 7 keys the Service Worker needs, so the SW bundle stays
 * lightweight (~KB) instead of inlining all 20 full dictionaries (~500 KB).
 * Run via `bun run build:sw` (which runs this before the Vite SW bundle).
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const LOCALES_DIR = join(__dirname, "..", "app", "locales");
const OUT_FILE = join(__dirname, "..", "app", "service-worker", "push-strings.generated.ts");

const files = readdirSync(LOCALES_DIR).filter((f) => f.endsWith(".json"));

const strings = {};
for (const file of files) {
  const lang = file.replace(/\.json$/, "");
  const json = JSON.parse(readFileSync(join(LOCALES_DIR, file), "utf8"));
  const push = json?.notifications?.push;
  if (!push || typeof push !== "object") {
    console.warn(`[build-sw] ${file}: missing notifications.push, skipped`);
    continue;
  }
  strings[lang] = push;
}

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(
  OUT_FILE,
  `// GENERATED by scripts/build-sw-push-strings.mjs — DO NOT EDIT.\n` +
    `// Source: app/locales/*.json (notifications.push). Regenerate via \`bun run build:sw\`.\n` +
    `export const PUSH_STRINGS: Record<string, Record<string, string>> = ${JSON.stringify(strings, null, 2)};\n`,
);
console.log(`[build-sw] wrote ${OUT_FILE} (${Object.keys(strings).length} languages)`);
